#!/usr/bin/env python3
"""The Lazaxian letters for the game-start flood (0.58.3, owner: "replace the 0s and 1s with 0s, 1s, and random
lazaxian font").

Each letter A-Z of the owner's Lazaxian font (assets/fonts/Lazaxian-Bold.ttf) is drawn large, cropped and fitted into
the flood's 7 x 11 cell (aspect kept, the short side stretched up to 1.5x, centred), one bit per cell pixel (covered
more than 30%).

Output: src/ui/gen/laz_glyphs.inc - kLazGlyphs[26][11], bit x = column x (0 = left).
"""
import os
import numpy as np
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT = os.path.join(ROOT, 'assets', 'fonts', 'Lazaxian-Bold.ttf')
OUT = os.path.join(ROOT, 'src', 'ui', 'gen', 'laz_glyphs.inc')
COLS, ROWS, THRESHOLD, STRETCH = 7, 11, 0.3, 1.5


def letter(font, ch):
    im = Image.new('L', (400, 400), 0)
    ImageDraw.Draw(im).text((60, 40), ch, font=font, fill=255)
    a = np.array(im)
    ys, xs = np.nonzero(a > 40)
    return a[ys.min():ys.max() + 1, xs.min():xs.max() + 1] / 255.0


def fit(a):
    h, w = a.shape
    s = min(COLS / w, ROWS / h)
    gw = min(COLS, max(1, round(w * s * (STRETCH if w * s < COLS - 0.5 else 1))))
    gh = min(ROWS, max(1, round(h * s * (STRETCH if h * s < ROWS - 0.5 else 1))))
    out = np.zeros((ROWS, COLS), bool)
    ox, oy = (COLS - gw) // 2, (ROWS - gh) // 2
    for y in range(gh):
        for x in range(gw):
            y0 = int(y * h / gh)
            y1 = max(y0 + 1, int((y + 1) * h / gh))
            x0 = int(x * w / gw)
            x1 = max(x0 + 1, int((x + 1) * w / gw))
            out[oy + y, ox + x] = a[y0:y1, x0:x1].mean() > THRESHOLD
    return out


def main():
    font = ImageFont.truetype(FONT, 240)
    lines = ['// Generated by tools/gen_laz_glyphs.py - the Lazaxian letters A-Z fitted into the game-start flood\'s 7 x 11',
             '// cell (bit x = column x).',
             'const uint8_t kLazGlyphs[26][11] = {']
    for c in range(26):
        m = fit(letter(font, chr(65 + c)))
        rows = [sum(1 << x for x in range(COLS) if m[y, x]) for y in range(ROWS)]
        lines.append('  {' + ', '.join(f'0x{r:02x}' for r in rows) + '},  // ' + chr(65 + c))
    lines.append('};')
    with open(OUT, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print('wrote', OUT)


if __name__ == '__main__':
    main()
